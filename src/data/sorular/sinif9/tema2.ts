/** Kareli zemin yardımcıları: sol üst köşe (30, 20), kare kenarı 20 birim */
const KX = (c: number) => 30 + c * 20
const KY = (s: number) => 20 + s * 20
function kareli(sutun: number, satir: number) {
  let d = ''
  for (let i = 0; i <= sutun; i++) d += `M${KX(i)} ${KY(0)} V${KY(satir)} `
  for (let j = 0; j <= satir; j++) d += `M${KX(0)} ${KY(j)} H${KX(sutun)} `
  return `<path d="${d.trim()}" stroke-width="1" stroke-opacity="0.3"/>`
}
const kOk = (c1: number, s1: number, c2: number, s2: number, renk: 'v' | 'i' | 't' = 'v') =>
  ok(KX(c1), KY(s1), KX(c2), KY(s2), renk, 2.5)
const nokta = (x: number, y: number, yc = 4.5) => `<circle cx="${x}" cy="${y}" r="${yc}" class="f-t" stroke="none"/>`

