/** Lamba sembolü: (x, y) merkezli, içinde çarpı olan daire (yarıçap 16) */
const lamba = (x: number, y: number) =>
  `<circle cx="${x}" cy="${y}" r="16" stroke-width="3"/><path d="M${x - 11} ${y - 11} L${x + 11} ${y + 11} M${x + 11} ${y - 11} L${x - 11} ${y + 11}" stroke-width="2"/>`

/** Ölçü aleti (ampermetre / voltmetre): (x, y) merkezli daire ve içinde harf (yarıçap 16) */
const olcer = (x: number, y: number, harf: string) =>
  `<circle cx="${x}" cy="${y}" r="16" stroke-width="2.5"/>` + yazi(x, y + 5, harf, { boy: 15, hiza: 'middle' })

/** Yatay pil: x'ten x+14'e; artiSolda ise uzun (+) plaka solda */
const pilYatay = (x: number, y: number, artiSolda = true) => {
  const uzun = artiSolda ? x : x + 14
  const kisa = artiSolda ? x + 14 : x
  return `<line x1="${uzun}" y1="${y - 18}" x2="${uzun}" y2="${y + 18}" stroke-width="3"/><line x1="${kisa}" y1="${y - 9}" x2="${kisa}" y2="${y + 9}" stroke-width="6"/>`
}

/** Devre düğüm noktası */
const dugum = (x: number, y: number) => `<circle cx="${x}" cy="${y}" r="4" class="f-t" stroke="none"/>`

/** Anahtar ucu (küçük kontak noktası) */
const kontak = (x: number, y: number) => `<circle cx="${x}" cy="${y}" r="3.5" class="f-t" stroke="none"/>`

/** Toprak sembolü: (x, y) üst çizginin ortası */
const toprak = (x: number, y: number) =>
  cizgi(x - 20, y, x + 20, y, { k: 3 }) + cizgi(x - 12, y + 8, x + 12, y + 8, { k: 3 }) + cizgi(x - 5, y + 16, x + 5, y + 16, { k: 3 })

